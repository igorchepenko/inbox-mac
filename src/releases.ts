/** 2026-10-26 → 26.10.2026. Неразборчивое значение возвращается как есть */
export function fmtReleaseDate(iso: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
  return m ? `${m[3]}.${m[2]}.${m[1]}` : iso;
}

// ── Окно новинок при первом запуске новой версии ──

/** Одно значение на приложение, не на профиль: смена профиля окно не повторяет */
export const SEEN_KEY = "inbox.releases-seen";

/** Показывать ли окно: версия ещё не показана. Недоступное хранилище (null) окно не показывает, иначе оно будет вылезать на каждом запуске */
export function shouldShowReleases(seen: string | null | undefined, current: string): boolean {
  return seen !== null && seen !== undefined && seen !== current;
}

/** Окно открыто для этой версии: больше само не появится. false, если запомнить не удалось */
export function markReleasesSeen(version: string): boolean {
  try {
    localStorage.setItem(SEEN_KEY, version);
    return true;
  } catch {
    return false;
  }
}

/** Что запомнено: строка, "" если ещё ничего, null если хранилище недоступно */
export function readReleasesSeen(): string | null {
  try {
    return localStorage.getItem(SEEN_KEY) ?? "";
  } catch {
    return null;
  }
}
